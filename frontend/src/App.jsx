import { useState } from "react";
import InputForm from "./components/InputForm";
import ResultCard from "./components/ResultCard";

function App() {
  const [result, setResult] = useState(null);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState("");
  const [analyzedPhoto, setAnalyzedPhoto] = useState(null);

  const handleSubmit = async (formData, photoUrl) => {
    setLoading(true);
    setResult(null);
    setError("");
    setAnalyzedPhoto(photoUrl);

    try {
      const response = await fetch(`${import.meta.env.VITE_API_URL}/analyze`, {
        method: "POST",
        body: formData,
      });
      const data = await response.json().catch(() => ({}));
      if (!response.ok || data.error) {
        setError(
          data.error ||
            "That meal couldn't be analyzed. Try a clearer, well-lit photo, or describe the meal in words."
        );
      } else {
        setResult(data);
      }
    } catch (err) {
      console.error("Error:", err);
      setError("Couldn't reach the server. Check your connection and try again.");
    } finally {
      setLoading(false);
    }
  };

  return (
    <div className="page">
      <header className="masthead">
        <span className="brand">Smart Meal Analyzer</span>
        <a
          className="source-link"
          href="https://github.com/AnandPabbineedi/smart-meal-analyzer"
          target="_blank"
          rel="noreferrer"
        >
          View source
        </a>
      </header>

      <main className="layout">
        <section className="intro">
          <h1 className="headline">Know what's on your plate.</h1>
          <p className="lede">
            Snap your meal or describe it. You'll get calories, macros and a
            health score in a few seconds.
          </p>
          <InputForm onSubmit={handleSubmit} loading={loading} />
        </section>

        <section className="result-col" aria-live="polite">
          <ResultCard
            result={result}
            loading={loading}
            error={error}
            photo={analyzedPhoto}
          />
        </section>
      </main>

      <footer className="footnote">
        Estimates are generated by Google Gemini from your photo or description.
        Use them as a guide, not medical advice.
      </footer>
    </div>
  );
}

export default App;
